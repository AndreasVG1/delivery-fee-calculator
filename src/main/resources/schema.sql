-- H2 schema for the Delivery Fee Calculator.
--
-- Schema choices:
-- * Imported observation measurements use DECIMAL(8, 3).
-- * Fee amounts use DECIMAL(10, 2), matching the current EUR fee rules.
-- * A station's WMO code and observation timestamp identify one observation.
-- * A vehicle type and phenomenon identify one phenomenon fee rule.
-- * requested_at is nullable because the REST request datetime is optional.
-- * A calculation is considered successful when error_message IS NULL.
-- * mapped_city is derived from the station name; only observations from a
--   city's mapped station can be referenced by that city's calculations.
-- * Threshold non-overlap is a cross-row rule and must be validated by the
--   application while serializing concurrent rule writes. H2 has no
--   declarative exclusion constraint for this rule.

CREATE TABLE weather_observation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_name VARCHAR(255) NOT NULL,
    wmo_code VARCHAR(32) NOT NULL,
    air_temperature DECIMAL(8, 3) NOT NULL,
    wind_speed DECIMAL(8, 3) NOT NULL,
    phenomenon VARCHAR(255) NOT NULL,
    observed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    mapped_city VARCHAR(16) GENERATED ALWAYS AS (
        CASE station_name
            WHEN 'Tallinn-Harku' THEN 'TALLINN'
            WHEN 'Tartu-Tõravere' THEN 'TARTU'
            WHEN 'Pärnu' THEN 'PÄRNU'
            ELSE NULL
        END
    ),

    CONSTRAINT uq_weather_observation_wmo_time
        UNIQUE (wmo_code, observed_at),
    CONSTRAINT uq_weather_observation_id_city
        UNIQUE (id, mapped_city)
);

CREATE INDEX ix_weather_observation_station_time
    ON weather_observation (station_name, observed_at);

CREATE TABLE regional_base_fee (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city VARCHAR(16) NOT NULL,
    vehicle_type VARCHAR(16) NOT NULL,
    fee_amount DECIMAL(10, 2) NOT NULL,

    CONSTRAINT ck_regional_base_fee_city
        CHECK (city IN ('TALLINN', 'TARTU', 'PÄRNU')),
    CONSTRAINT ck_regional_base_fee_vehicle
        CHECK (vehicle_type IN ('CAR', 'SCOOTER', 'BIKE')),
    CONSTRAINT ck_regional_base_fee_nonnegative
        CHECK (fee_amount >= 0),
    CONSTRAINT uq_regional_base_fee_city_vehicle
        UNIQUE (city, vehicle_type)
);

CREATE TABLE temperature_fee_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_type VARCHAR(16) NOT NULL,
    lower_threshold DECIMAL(8, 3),
    upper_threshold DECIMAL(8, 3),
    lower_inclusive BOOLEAN NOT NULL,
    upper_inclusive BOOLEAN NOT NULL,
    fee_amount DECIMAL(10, 2) NOT NULL,

    CONSTRAINT ck_temperature_rule_vehicle
        CHECK (vehicle_type IN ('CAR', 'SCOOTER', 'BIKE')),
    CONSTRAINT ck_temperature_rule_has_bound
        CHECK (lower_threshold IS NOT NULL OR upper_threshold IS NOT NULL),
    CONSTRAINT ck_temperature_rule_valid_bounds
        CHECK (
            lower_threshold IS NULL
            OR upper_threshold IS NULL
            OR lower_threshold < upper_threshold
            OR (
                lower_threshold = upper_threshold
                AND lower_inclusive
                AND upper_inclusive
            )
        ),
    CONSTRAINT ck_temperature_rule_nonnegative_fee
        CHECK (fee_amount >= 0)
);

CREATE INDEX ix_temperature_fee_rule_vehicle
    ON temperature_fee_rule (vehicle_type);

CREATE TABLE wind_fee_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_type VARCHAR(16) NOT NULL,
    lower_threshold DECIMAL(8, 3),
    upper_threshold DECIMAL(8, 3),
    lower_inclusive BOOLEAN NOT NULL,
    upper_inclusive BOOLEAN NOT NULL,
    outcome VARCHAR(16) NOT NULL,
    fee_amount DECIMAL(10, 2) NOT NULL,

    CONSTRAINT ck_wind_rule_vehicle
        CHECK (vehicle_type IN ('CAR', 'SCOOTER', 'BIKE')),
    CONSTRAINT ck_wind_rule_has_bound
        CHECK (lower_threshold IS NOT NULL OR upper_threshold IS NOT NULL),
    CONSTRAINT ck_wind_rule_valid_bounds
        CHECK (
            lower_threshold IS NULL
            OR upper_threshold IS NULL
            OR lower_threshold < upper_threshold
            OR (
                lower_threshold = upper_threshold
                AND lower_inclusive
                AND upper_inclusive
            )
        ),
    CONSTRAINT ck_wind_rule_outcome
        CHECK (outcome IN ('SURCHARGE', 'FORBIDDEN')),
    CONSTRAINT ck_wind_rule_nonnegative_fee
        CHECK (fee_amount >= 0),
    CONSTRAINT ck_wind_rule_forbidden_fee
        CHECK (outcome <> 'FORBIDDEN' OR fee_amount = 0)
);

CREATE INDEX ix_wind_fee_rule_vehicle
    ON wind_fee_rule (vehicle_type);

CREATE TABLE phenomenon_fee_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_type VARCHAR(16) NOT NULL,
    phenomenon VARCHAR(16) NOT NULL,
    outcome VARCHAR(16) NOT NULL,
    fee_amount DECIMAL(10, 2) NOT NULL,

    CONSTRAINT ck_phenomenon_rule_vehicle
        CHECK (vehicle_type IN ('CAR', 'SCOOTER', 'BIKE')),
    CONSTRAINT ck_phenomenon_rule_phenomenon
        CHECK (phenomenon IN ('SNOW', 'SLEET', 'RAIN', 'GLAZE', 'HAIL', 'THUNDER', 'OTHER')),
    CONSTRAINT ck_phenomenon_rule_outcome
        CHECK (outcome IN ('SURCHARGE', 'FORBIDDEN')),
    CONSTRAINT ck_phenomenon_rule_nonnegative_fee
        CHECK (fee_amount >= 0),
    CONSTRAINT ck_phenomenon_rule_forbidden_fee
        CHECK (outcome <> 'FORBIDDEN' OR fee_amount = 0),
    CONSTRAINT uq_phenomenon_rule_vehicle_phenomenon
        UNIQUE (vehicle_type, phenomenon)
);

CREATE INDEX ix_phenomenon_fee_rule_vehicle
    ON phenomenon_fee_rule (vehicle_type);

CREATE TABLE delivery_fee_calculation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requested_at TIMESTAMP(6) WITH TIME ZONE,
    calculated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    city VARCHAR(16) NOT NULL,
    vehicle_type VARCHAR(16) NOT NULL,
    weather_observation_id BIGINT,
    rbf DECIMAL(10, 2),
    atef DECIMAL(10, 2),
    wsef DECIMAL(10, 2),
    wpef DECIMAL(10, 2),
    total_fee DECIMAL(10, 2),
    error_message VARCHAR(500),

    CONSTRAINT fk_delivery_fee_calculation_weather
        FOREIGN KEY (weather_observation_id, city)
        REFERENCES weather_observation (id, mapped_city),
    CONSTRAINT ck_delivery_fee_calculation_city
        CHECK (city IN ('TALLINN', 'TARTU', 'PÄRNU')),
    CONSTRAINT ck_delivery_fee_calculation_vehicle
        CHECK (vehicle_type IN ('CAR', 'SCOOTER', 'BIKE')),
    CONSTRAINT ck_delivery_fee_calculation_total_on_error
        CHECK (error_message IS NULL OR total_fee IS NULL),
    CONSTRAINT ck_delivery_fee_calculation_complete_success
        CHECK (
            error_message IS NOT NULL
            OR (
                weather_observation_id IS NOT NULL
                AND rbf IS NOT NULL
                AND atef IS NOT NULL
                AND wsef IS NOT NULL
                AND wpef IS NOT NULL
                AND total_fee IS NOT NULL
                AND total_fee = rbf + atef + wsef + wpef
            )
        )
);

CREATE INDEX ix_delivery_fee_calculation_lookup
    ON delivery_fee_calculation (city, vehicle_type, error_message, weather_observation_id);
